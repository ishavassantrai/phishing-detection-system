#imports the modules pandas for CSV handling
#dataset for coverting CVS file to huggingface dataset
#transformers for importing tokenizer, model, training args and traning class
#sklearn for calculating accuacy, precision, recall and F1
import pandas as pd
from datasets import Dataset
from transformers import RobertaTokenizerFast, RobertaForSequenceClassification, TrainingArguments, Trainer
from sklearn.metrics import accuracy_score, precision_recall_fscore_support

# allows synethic phishing dataset csv file to be uploaded
from google.colab import files
uploaded = files.upload()

# loads the file keeping only the Body and label coloumns
df = pd.read_csv("Completed_dataset_v2.csv")
df = df[["Body", "label"]].dropna()
#from the label section will mark phishing as the value of 1 and non-phishing as 0
df["label"] = df["label"].map({"phishing": 1, "non-phishing": 0})

#splits the data into a 80% training and 20% validation
#42 is assigned to random_state to ensure the split is the same everytime
from sklearn.model_selection import train_test_split
train_texts, val_texts = train_test_split(df, test_size=0.2, random_state=42)

#converts panda dataframes into huggingface datasets
train_ds = Dataset.from_pandas(train_texts)
val_ds = Dataset.from_pandas(val_texts)

#loads the tokeniser for roBERTa into tokens compatible with model
tokenizer = RobertaTokenizerFast.from_pretrained("roberta-base")

#tokenises the email body text adding paddings and truncations to ensure that all inputs are the same (512)
def tokenize(example):
    return tokenizer(example["Body"], padding="max_length", truncation=True, max_length=512)


#coverts the database to Pytorch tensors, specifying which fields to inclyde for training
train_ds = train_ds.map(tokenize, batched=True)
val_ds = val_ds.map(tokenize, batched=True)

train_ds.set_format(type="torch", columns=["input_ids", "attention_mask", "label"])
val_ds.set_format(type="torch", columns=["input_ids", "attention_mask", "label"])

#loads the roBERTa with a classification head of 2 outputs phishing or not
model = RobertaForSequenceClassification.from_pretrained("roberta-base", num_labels=2)

#defines how to evalutate the models performance after each epoch using accuray, precision, recall and f1 score
def compute_metrics(pred):
    labels = pred.label_ids
    preds = pred.predictions.argmax(-1)
    acc = accuracy_score(labels, preds)
    precision, recall, f1, _ = precision_recall_fscore_support(labels, preds, average="binary")
    return {"accuracy": acc, "precision": precision, "recall": recall, "f1": f1}

#huggingface trainer trains based on:
#saving and evalutating after each epoch
#using batch size of 8
#training for a total of 3 epoches
#saves best model using f1 score

training_args = TrainingArguments(
    output_dir="/content/roberta-phishing",
    evaluation_strategy="epoch",
    save_strategy="epoch",
    num_train_epochs=3,
    per_device_train_batch_size=8,
    per_device_eval_batch_size=8,
    logging_dir="/content/logs",
    load_best_model_at_end=True,
    metric_for_best_model="f1",
    report_to= "none"
)

#creates an instance of trainer using args set up
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_ds,
    eval_dataset=val_ds,
    tokenizer=tokenizer,
    compute_metrics=compute_metrics,
)

trainer.train()

